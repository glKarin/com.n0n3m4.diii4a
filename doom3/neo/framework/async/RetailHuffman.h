class Huffman {
    struct Node { uint64_t weight; int child[2]; int parent; int edge; } nodes[511];
    int root;
public:
    explicit Huffman(const uint32_t (&frequencies)[256]) {
        int queue[256], count = 0;
        for (int n = 0; n < 511; ++n) {
            nodes[n].child[0] = nodes[n].child[1] = nodes[n].parent = -1;
            nodes[n].edge = 0;
            if (n < 256) nodes[n].weight = frequencies[n];
            else {
                const int left = queue[0], right = queue[1];
                for (int i = 2; i < count; ++i) queue[i - 2] = queue[i];
                count -= 2;
                nodes[n].child[0] = left; nodes[n].child[1] = right;
                nodes[left].parent = nodes[right].parent = n;
                nodes[right].edge = 1;
                nodes[n].weight = nodes[left].weight + nodes[right].weight;
            }
            // New nodes precede equal weights, including the initial leaves.
            int at = 0;
            while (at < count && nodes[queue[at]].weight < nodes[n].weight) ++at;
            for (int i = count; i > at; --i) queue[i] = queue[i - 1];
            queue[at] = n; ++count;
        }
        root = queue[0];
    }
    bool Encode(const uint8_t* input, size_t size, uint8_t* output, size_t capacity, size_t& written) const {
        size_t bits = 0;
        std::memset(output, 0, capacity);
        for (size_t i = 0; i < size; ++i) {
            uint8_t path[256]; int length = 0;
            for (int n = input[i]; nodes[n].parent >= 0; n = nodes[n].parent) path[length++] = nodes[n].edge;
            if (bits + length > capacity * 8) return false;
            while (length) { output[bits >> 3] |= path[--length] << (bits & 7); ++bits; }
        }
        written = (bits + 7) / 8;
        return true;
    }
    bool Decode(const uint8_t* input, size_t size, uint8_t* output, size_t expected, size_t& consumed) const {
        size_t bits = 0;
        for (size_t i = 0; i < expected; ++i) {
            int n = root;
            while (n >= 256) {
                if (bits >= size * 8) return false;
                n = nodes[n].child[(input[bits >> 3] >> (bits & 7)) & 1]; ++bits;
            }
            output[i] = static_cast<uint8_t>(n);
        }
        consumed = (bits + 7) / 8;
        return true;
    }
};
