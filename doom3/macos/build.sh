set -euo pipefail
SOURCE_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
BUILD_DIR="${ETQW_BUILD_DIR:-$SOURCE_ROOT/build-macos}"
DEPLOYMENT_TARGET="${MACOSX_DEPLOYMENT_TARGET:-$(sw_vers -productVersion)}"
cmake -S "$SOURCE_ROOT" -B "$BUILD_DIR" -G Ninja \
  -DCMAKE_BUILD_TYPE=RelWithDebInfo -DCMAKE_OSX_ARCHITECTURES=arm64 \
  -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET" \
  -DBUILD_D3=OFF -DBUILD_D3_MOD=OFF -DBUILD_Q4=OFF -DBUILD_Q4_MOD=OFF \
  -DBUILD_PREY=OFF -DBUILD_ETQW=ON -DCONSOLE=ON -DIMGUI=OFF \
  -DUSE_SYSTEM_CURL=ON -DUSE_SYSTEM_FREETYPE=ON "$@"
cmake --build "$BUILD_DIR" --target ETQW etqwgame -j "${ETQW_BUILD_JOBS:-6}"
cmake -S "$SOURCE_ROOT/doom3/neo/externlibs/openal-soft" -B "$BUILD_DIR/openal" -G Ninja \
  -DCMAKE_POLICY_VERSION_MINIMUM=3.5 -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_OSX_ARCHITECTURES=arm64 -DCMAKE_OSX_DEPLOYMENT_TARGET="$DEPLOYMENT_TARGET" \
  -DALSOFT_EXAMPLES=OFF -DALSOFT_UTILS=OFF -DALSOFT_TESTS=OFF \
  -DALSOFT_BACKEND_COREAUDIO=ON -DALSOFT_REQUIRE_OBOE=OFF -DALSOFT_BACKEND_OBOE=OFF \
  -DALSOFT_REQUIRE_OPENSL=OFF -DALSOFT_BACKEND_OPENSL=OFF
cmake --build "$BUILD_DIR/openal" -j "${ETQW_BUILD_JOBS:-6}"
